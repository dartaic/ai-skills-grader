function levelFromAvg(avg) {
  if (avg < 1) return 0;
  if (avg < 1.5) return 1;
  if (avg < 2.5) return 2;
  return 3;
}
function avgOf(arr) { return arr.length ? arr.reduce((a, b) => a + b, 0) / arr.length : null; }

function computeFromPoints(points) {
  const criteriaAvg = {};
  CRIT_ORDER.forEach(k => { criteriaAvg[k] = avgOf(points[k] || []); });
  const known = CRIT_ORDER.map(k => criteriaAvg[k]).filter(v => v !== null);
  const overallAvg = known.length ? known.reduce((a, b) => a + b, 0) / known.length : null;
  const overallLevel = overallAvg !== null ? levelFromAvg(overallAvg) : null;
  return { criteriaAvg, overallAvg, overallLevel };
}

// Детерминированный псевдослучайный генератор (mulberry32) — чтобы порядок вариантов
// у каждого сотрудника был свой, но стабильный между перезагрузками страницы.
function mulberry32(seed) {
  return function () {
    seed |= 0; seed = (seed + 0x6D2B79F5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
function seededShuffle(arr, seed) {
  const rng = mulberry32(seed);
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

// Кейсы под набор ролей одного человека: если роль одна — оба её кейса; если ролей
// несколько — по одному (первому) кейсу с каждой роли, не больше 3 кейсов суммарно,
// чтобы уложиться в ~20 минут.
function casesForRoles(roles) {
  const validRoles = roles.filter(r => CASE_SET_BY_ROLE[r]);
  if (validRoles.length === 0) return [];
  if (validRoles.length === 1) {
    const setKey = CASE_SET_BY_ROLE[validRoles[0]];
    return CASES[setKey].map(c => ({ ...c, roleKey: validRoles[0] }));
  }
  const out = [];
  for (const r of validRoles) {
    if (out.length >= 3) break;
    const setKey = CASE_SET_BY_ROLE[r];
    const c = CASES[setKey][0];
    out.push({ ...c, roleKey: r });
  }
  return out;
}

